/**
 * Declarative mapping between ATLAS domain objects and Airtable tables.
 *
 * Each entity names its Airtable table and, for every domain key, the Airtable
 * field name and how to convert it. Field names are resolved to field IDs via
 * the generated schema so the app keeps working if a field is renamed and the
 * schema is regenerated. A unit test checks every name here exists in the
 * live-schema snapshot.
 */
import type { AirtableTableName } from "./airtable/schema.generated";

export type FieldKind =
  | "text"
  | "number"
  | "currency" // stored in Airtable as dollars, in ATLAS as integer cents
  | "percent" // fraction, 0.3 = 30%
  | "date" // YYYY-MM-DD
  | "datetime" // ISO string
  | "checkbox"
  | "select"
  | "multiselect"
  | "links" // array of record IDs
  | "collaborator" // read-only display name
  | "attachments" // read-only [{url, filename}]
  | "computed"; // formula/rollup, read-only

export interface FieldSpec {
  field: string;
  kind: FieldKind;
  readOnly?: boolean;
  /** Kept in ATLAS's own database only; there is no Airtable column for it. */
  local?: boolean;
}

export interface EntitySpec {
  table: AirtableTableName;
  primary: string; // domain key used as display name
  fields: Record<string, FieldSpec>;
}

const mk =
  <K extends FieldKind>(kind: K) =>
  (field: string) => ({ field, kind });
const t = mk("text");
const n = mk("number");
const c = mk("currency");
const p = mk("percent");
const d = mk("date");
const dt = mk("datetime");
const b = mk("checkbox");
const s = mk("select");
const l = mk("links");
/** A field that exists only in ATLAS's own database (added after the move off Airtable). */
const own =
  <K extends FieldKind>(kind: K) =>
  (field: string) => ({ field, kind, local: true as const });
const ownText = own("text");

function ro(field: string): { field: string; kind: "computed"; readOnly: true };
function ro<K extends FieldKind>(field: string, kind: K): { field: string; kind: K; readOnly: true };
function ro(field: string, kind: FieldKind = "computed") {
  return { field, kind, readOnly: true as const };
}

